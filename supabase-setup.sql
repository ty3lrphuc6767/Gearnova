-- Các hàm này cho phép website thêm/xóa sản phẩm mà không cần cấp role admin
-- cho từng email. Chỉ tài khoản đã đăng nhập và có đúng mật khẩu mới gọi được.
create or replace function public.admin_add_product(
  p_admin_password text,
  p_name text,
  p_category text,
  p_price bigint,
  p_image_url text,
  p_description text,
  p_specs jsonb
)
returns public.products
language plpgsql
security definer
set search_path = public
as $$
declare
  created_product public.products;
begin
  if p_admin_password <> 'GearNova@2026' then
    raise exception 'Sai mật khẩu quản trị.';
  end if;

  if coalesce(p_category, '') not in ('CPU', 'GPU', 'RAM', 'SSD', 'GEAR') then
    raise exception 'Danh mục không hợp lệ.';
  end if;

  if coalesce(btrim(p_name), '') = '' or p_price is null or p_price < 0 then
    raise exception 'Dữ liệu sản phẩm không hợp lệ.';
  end if;

  insert into public.products (name, category, price, image_url, description, specs)
  values (
    btrim(p_name),
    p_category,
    p_price,
    nullif(btrim(coalesce(p_image_url, '')), ''),
    coalesce(p_description, ''),
    coalesce(p_specs, '[]'::jsonb)
  )
  returning * into created_product;

  return created_product;
end;
$$;

